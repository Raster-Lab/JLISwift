    @Test("Decode extracts the ICC profile cjpeg embedded (byte-exact)")
    func decodeICCFromCjpeg() throws {
        let img = try JLIDecoder().decode(from: Self.iccJPEG)
        #expect(img.iccProfile == Self.iccProfile300, "extracted ICC profile mismatch")
        #expect(img.exif == nil)
    }

    @Test("ICC + Exif round-trip through encode/decode (color, grayscale)")
    func roundTripMetadata() throws {
        let icc = (0..<500).map { UInt8(($0 * 11 + 7) & 0xFF) }
        let exif = (0..<120).map { UInt8(($0 * 5 + 1) & 0xFF) }
        // Color
        let w = 16, h = 16
        let rgb = (0..<(w * h * 3)).map { UInt8($0 & 0xFF) }
        let cImg = try JLIImage(width: w, height: h, pixelFormat: .uint8, colorModel: .rgb,
                                data: rgb, iccProfile: icc, exif: exif)
        let cDec = try JLIDecoder().decode(from: try JLIEncoder().encode(cImg, configuration: .default))
        #expect(cDec.iccProfile == icc, "color ICC round-trip")
        #expect(cDec.exif == exif, "color Exif round-trip")
        // Grayscale
        let gray = (0..<(w * h)).map { UInt8($0 & 0xFF) }
        let gImg = try JLIImage(width: w, height: h, pixelFormat: .uint8, colorModel: .grayscale,
                                data: gray, iccProfile: icc, exif: exif)
        var gcfg = JLIEncoderConfiguration.default; gcfg.chromaSubsampling = .yuv400
        let gDec = try JLIDecoder().decode(from: try JLIEncoder().encode(gImg, configuration: gcfg))
        #expect(gDec.iccProfile == icc && gDec.exif == exif, "grayscale metadata round-trip")
    }

    @Test("Large ICC profile round-trips across multiple APP2 segments")
    func multiSegmentICC() throws {
        // 140000 bytes > 65519 → 3 chunks; reassembly must restore it exactly.
        let icc = (0..<140000).map { UInt8(($0 &* 2654435761 >> 13) & 0xFF) }
        let w = 8, h = 8
        let img = try JLIImage(width: w, height: h, pixelFormat: .uint8, colorModel: .grayscale,
                               data: [UInt8](repeating: 128, count: w * h), iccProfile: icc)
        var cfg = JLIEncoderConfiguration.default; cfg.chromaSubsampling = .yuv400
        let dec = try JLIDecoder().decode(from: try JLIEncoder().encode(img, configuration: cfg))
        #expect(dec.iccProfile?.count == icc.count, "reassembled ICC length")
        #expect(dec.iccProfile == icc, "reassembled multi-segment ICC mismatch")
    }

    @Test("Lossless mode carries ICC + Exif")
    func losslessMetadata() throws {
        let icc = (0..<400).map { UInt8(($0 * 3) & 0xFF) }
        let exif = (0..<64).map { UInt8($0) }
        let w = 10, h = 8
        let gray = (0..<(w * h)).map { UInt8(($0 * 7) & 0xFF) }
        let img = try JLIImage(width: w, height: h, pixelFormat: .uint8, colorModel: .grayscale,
                               data: gray, iccProfile: icc, exif: exif)
        var cfg = JLIEncoderConfiguration.default
        cfg.lossless = true; cfg.chromaSubsampling = .yuv400
        let dec = try JLIDecoder().decode(from: try JLIEncoder().encode(img, configuration: cfg))
        #expect(dec.data == gray, "lossless pixels must stay exact")
        #expect(dec.iccProfile == icc && dec.exif == exif, "lossless metadata round-trip")
    }

    @Test("No metadata in, no metadata out")
    func absentMetadata() throws {
        let w = 8, h = 8
        let img = try JLIImage(width: w, height: h, pixelFormat: .uint8, colorModel: .grayscale,
                               data: [UInt8](repeating: 100, count: w * h))
        var cfg = JLIEncoderConfiguration.default; cfg.chromaSubsampling = .yuv400
        let dec = try JLIDecoder().decode(from: try JLIEncoder().encode(img, configuration: cfg))
        #expect(dec.iccProfile == nil && dec.exif == nil)
    }
