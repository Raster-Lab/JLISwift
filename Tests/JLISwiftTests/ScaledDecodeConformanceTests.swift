    @Test("1/2 scaled decode agrees with djpeg -scale 1/2")
    func scale2VsDjpeg() throws {
        var cfg = JLIDecoderConfiguration.default; cfg.scale = 2
        let img = try JLIDecoder().decode(from: Self.sdJPEG, configuration: cfg)
        #expect(img.width == Self.sdW / 2 && img.height == Self.sdH / 2)
        #expect(img.data.count == Self.sdDJ2.count)
        var maxErr = 0
        for i in 0..<img.data.count { maxErr = max(maxErr, abs(Int(img.data[i]) - Int(Self.sdDJ2[i]))) }
        #expect(maxErr <= 6, "1/2 scaled decode vs djpeg max err \(maxErr)")
    }

    @Test("1/4 scaled decode agrees with djpeg -scale 1/4")
    func scale4VsDjpeg() throws {
        var cfg = JLIDecoderConfiguration.default; cfg.scale = 4
        let img = try JLIDecoder().decode(from: Self.sdJPEG, configuration: cfg)
        #expect(img.width == Self.sdW / 4 && img.height == Self.sdH / 4)
        #expect(img.data.count == Self.sdDJ4.count)
        var maxErr = 0
        for i in 0..<img.data.count { maxErr = max(maxErr, abs(Int(img.data[i]) - Int(Self.sdDJ4[i]))) }
        #expect(maxErr <= 6, "1/4 scaled decode vs djpeg max err \(maxErr)")
    }
